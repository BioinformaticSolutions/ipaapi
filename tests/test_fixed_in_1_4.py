def test_recursive_skips_hidden_directories():
    root = pathlib.Path(tempfile.mkdtemp())
    (root / ".ipynb_checkpoints").mkdir()
    (root / "real.txt").write_text("x")
    (root / ".ipynb_checkpoints" / "real-checkpoint.txt").write_text("x")
    found = cli.discover_files(str(root), None, True)
    assert [p.name for p in found] == ["real.txt"]


# -- durability -------------------------------------------------------------


def test_the_token_cache_is_never_world_readable():
    path = os.path.join(tempfile.mkdtemp(), "token.json")
    TokenCache(path).put("cid", Credentials("secret", refresh_token="rt"))
    mode = stat.S_IMODE(os.stat(path).st_mode)
    assert not mode & (stat.S_IRGRP | stat.S_IROTH)


def test_a_corrupt_expiry_reads_as_a_miss():
    import json
    path = os.path.join(tempfile.mkdtemp(), "token.json")
    with open(path, "w") as fh:
        json.dump({"cid|PythonAPI|analysis.ingenuity.com":
                   {"access_token": "t", "expires_at": "not a number"}}, fh)
    assert TokenCache(path).get("cid", "PythonAPI", "analysis.ingenuity.com") is None


def test_a_non_utf8_byte_does_not_block_submission():
    path = os.path.join(tempfile.mkdtemp(), "log.tsv")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\t".join(history.FIELDS) + "\n")
    with open(path, "ab") as fh:
        fh.write("2026-09-12T10:00:00+00:00\t1\tP\tCaf\xe9\t\t\t\t\n".encode("cp1252"))
    assert cli._already_submitted("P", "anything", path) is None


def test_a_truncated_final_row_is_survivable():
    path = os.path.join(tempfile.mkdtemp(), "log.tsv")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\t".join(history.FIELDS) + "\n")
        fh.write("2026-09-12T10:00:00+00:00\t1\tP\tds\tobs\tsrc\tapp\thost\n")
        fh.write("2026-09-12T10:05:00+00:00\t2\n")
    rows = history.read(path)
    assert all(v is not None for row in rows for v in row.values())


def test_timestamps_sort_chronologically():
    stamps = [history._now() for _ in range(2)]
    assert stamps == sorted(stamps)
    assert stamps[0].endswith("+00:00")


def test_triage_does_not_claim_a_move_that_failed():
    root = pathlib.Path(tempfile.mkdtemp())
    (root / "a.txt").write_text("x")
    os.chmod(root, 0o555)
    try:
        t = Triage(root)
        t.mark_submitted(root / "a.txt")
        assert t.submitted == []
        assert "moved to submitted/" not in t.summary()
    finally:
        os.chmod(root, 0o755)


def test_an_error_note_never_overwrites_an_existing_one():
    root = pathlib.Path(tempfile.mkdtemp())
    (root / "run.txt").write_text("x")
    (root / "run.txt.error.txt").write_text("PRECIOUS")
    t = Triage(root)
    t.mark_failed(root / "run.txt.error.txt", "reason A")
    t.mark_failed(root / "run.txt", "reason B")
    assert (root / "failed" / "run.txt.error.txt").read_text() == "PRECIOUS"
