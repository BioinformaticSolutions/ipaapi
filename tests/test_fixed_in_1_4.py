"""Regressions for the defects found by reading the package through in 1.4.0.

Every test here failed before the corresponding fix. They are grouped by what
goes wrong for the user rather than by module, because that is what decides
whether a regression matters: the first group is IPA scoring an analysis on
data that is not what was meant, which is the failure this package exists to
prevent.
"""

import os
import pathlib
import stat
import tempfile

import pandas as pd
import pytest

from ipaapi import _payload, cli, history
from ipaapi.auth import Credentials, TokenCache
from ipaapi.client import (
    looks_like_gateway_timeout,
    looks_like_quota,
    _PLUS_AS_SPACE,
)
from ipaapi.dataset import Dataset, load_table
from ipaapi.errors import IPAError, MappingError
from ipaapi.mapping import ColumnMapping, Measurement, Observation
from ipaapi.models import MeasurementType as MT
from ipaapi.triage import Triage


def frame(**cols):
    return pd.DataFrame(cols, dtype=object)


def one_obs(column, mtype=MT.FOLD_CHANGE, **kw):
    return ColumnMapping(
        "ID", "ensembl", [Observation("o", [Measurement(column, mtype, **kw)])]
    )


def write(text, name="data.txt"):
    tmp = pathlib.Path(tempfile.mkdtemp()) / name
    tmp.write_text(text)
    return tmp


# -- wrong data reaching IPA ------------------------------------------------


@pytest.mark.parametrize("value", ["Inf", "-Inf", "inf"])
def test_infinite_fold_changes_are_refused(value):
    """DESeq2 and edgeR emit Inf where a group has zero counts."""
    f = frame(ID=["a", "b"], FC=["2.5", value])
    with pytest.raises(MappingError, match="infinite"):
        Dataset.from_frame(f, one_obs("FC"), name="d")


@pytest.mark.parametrize("mtype", [MT.RATIO, MT.LOG_RATIO, MT.INTENSITY, MT.OTHER])
def test_no_measurement_type_accepts_infinity(mtype):
    assert not mtype.is_plausible(float("inf"))
    assert not mtype.is_plausible(float("-inf"))


def test_a_text_column_declared_as_fold_change_is_refused():
    """The shape of a --FC that is one column off, pointing at gene symbols."""
    f = frame(ID=["ENSG1", "ENSG2"], Sym=["TP53", "BRCA1"])
    with pytest.raises(MappingError, match="not numbers and not blank"):
        Dataset.from_frame(f, one_obs("Sym"), name="d")


def test_the_whole_column_unreadable_says_so():
    f = frame(ID=["a", "b"], Sym=["TP53", "BRCA1"])
    with pytest.raises(MappingError, match="off by one"):
        Dataset.from_frame(f, one_obs("Sym"), name="d")


def test_excel_artefacts_are_refused():
    f = frame(ID=["a", "b", "c"], FC=["2.0", "#DIV/0!", "1,5"])
    with pytest.raises(MappingError, match="not numbers and not blank"):
        Dataset.from_frame(f, one_obs("FC"), name="d")


def test_blank_cells_are_still_allowed():
    """A missing measurement is honest; only unreadable text is the problem."""
    f = frame(ID=["a", "b", "c"], FC=["2.0", "", "NA"])
    assert Dataset.from_frame(f, one_obs("FC"), name="d")


def test_a_comma_in_a_column_name_does_not_reclassify_a_tsv():
    path = write(
        "Gene ID\tlog2FC, shrunken\tp-value\n"
        "ENSG1\t2.0\t0.01\nENSG2\t-3.0\t0.2\n"
    )
    assert list(load_table(path).columns) == ["Gene ID", "log2FC, shrunken", "p-value"]


def test_a_hash_prefixed_header_is_read_not_rejected():
    path = write("#Gene\tlogFC\tPValue\nTP53\t2.0\t0.01\nBRCA1\t-3.0\t0.2\n")
    assert list(load_table(path).columns) == ["Gene", "logFC", "PValue"]


def test_a_real_comment_line_is_still_diagnosed():
    path = write("# generated by pipeline v3, 2026-08-05\nID\tFC\na\t2.0\nb\t3.0\n")
    with pytest.raises(MappingError, match="--skip-rows"):
        load_table(path)


def test_duplicate_column_labels_are_refused():
    """Repeated labels shift values into the wrong measurement slots."""
    f = pd.DataFrame([[1, 2.0, 9.9, 0.01]], columns=["ID", "FC", "FC", "p"])
    mapping = ColumnMapping(
        "ID", "ensembl",
        [Observation("A", [Measurement("FC", MT.FOLD_CHANGE),
                           Measurement("p", MT.P_VALUE)])],
    )
    with pytest.raises(MappingError, match="more than once in the dataset"):
        mapping.validate(f, check_ranges=False)


@pytest.mark.parametrize("blank", ["-", ".", "", "NA", "null"])
def test_every_blank_spelling_is_sent_as_missing(blank):
    f = frame(ID=["a", "b"], FC=["2.0", blank])
    mapping = one_obs("FC")
    pairs = _payload.build_submission_pairs(f, mapping, "app", "proj", "ds")
    assert [v for k, v in pairs if k == "expvalue"] == ["2.0", "NaN"]


def test_float_typed_identifiers_lose_the_decimal():
    f = pd.DataFrame({"ID": [7157.0, 672.0], "FC": [2.0, 3.0]})
    mapping = ColumnMapping(
        "ID", "entrezgene",
        [Observation("o", [Measurement("FC", MT.FOLD_CHANGE)])],
    )
    pairs = _payload.build_submission_pairs(f, mapping, "app", "proj", "ds")
    assert [v for k, v in pairs if k == "geneid"] == ["7157", "672"]


@pytest.mark.parametrize("value", [0.5, 1.7, -0.3])
def test_gain_loss_is_a_code_not_a_scale(value):
    assert not MT.GAIN_LOSS.is_plausible(value)
    assert not MT.CLASSIFICATION.is_plausible(value)


def test_a_cutoff_keeps_its_precision():
    pairs = _payload.build_submission_pairs(
        frame(ID=["a"], FC=["2.0"]),
        one_obs("FC", cutoff=1234567.0), "app", "proj", "ds",
    )
    assert ("cutoff", "1234567") in pairs


def test_the_fdr_warning_mentions_the_cutoff():
    f = frame(ID=[str(i) for i in range(60)],
              FC=["2.0"] * 60,
              Q=[str(round(0.001 * i, 4)) for i in range(60)])
    mapping = ColumnMapping(
        "ID", "ensembl",
        [Observation("o", [Measurement("FC", MT.FOLD_CHANGE),
                           Measurement("Q", MT.FALSE_DISCOVERY, cutoff=0.05)])],
    )
    notes = "\n".join(Dataset.from_frame(f, mapping, name="d").warnings)
    assert "scale the cutoff with it" in notes


