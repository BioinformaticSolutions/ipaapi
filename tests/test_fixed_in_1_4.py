def test_an_error_page_is_not_reported_as_a_status():
    class Response:
        status_code = 200
        text = "<html><body>currently unavailable</body></html>"

    from ipaapi.client import IPAClient
    client = IPAClient.__new__(IPAClient)
    client._get = lambda *a, **k: Response()
    with pytest.raises(IPAError, match="did not return a status code"):
        client.status("x")


@pytest.mark.parametrize("name,expected", [
    ("NAD+ Signaling", "NAD+ Signaling"),
    ("Ca2+ transport", "Ca2+ transport"),
    ("Acute+Phase+Response", "Acute Phase Response"),
])
def test_entity_names_keep_a_chemical_plus(name, expected):
    assert _PLUS_AS_SPACE.sub(" ", name) == expected


def test_a_caller_session_keeps_its_adapters():
    import requests
    from requests.adapters import HTTPAdapter
    from ipaapi.client import IPAClient

    session = requests.Session()
    mine = HTTPAdapter(pool_maxsize=99)
    session.mount("https://", mine)
    IPAClient(Credentials("t"), session=session)
    assert session.get_adapter("https://x") is mine


