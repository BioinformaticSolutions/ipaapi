def test_observation_names_stay_distinct_through_the_final_trim():
    names = [
        "Estrus_vs_2dpp_Immature_cortical_ovarian_stroma_sampleA_Luminal_epithelium_zone",
        "Estrus_vs_2dpp_Immature_cortical_ovarian_stroma_sampleB_Luminal_epithelium_zone",
        "Unrelated_pilot_experiment_from_another_study_entirely_xyz",
    ]
    out = cli.observation_names(names)
    assert len(set(out)) == len(set(names))
    assert all(len(n) <= cli.MAX_OBSERVATION_NAME for n in out)


def test_a_name_is_never_trimmed_to_a_fragment():
    out = cli.observation_names(
        ["EstrusVs2dppImmatureCorticalOvarianStromaTissueSampleAlpha_rep"]
    )
    assert len(out[0].strip("._- ")) >= cli.MIN_STRIPPED_NAME


